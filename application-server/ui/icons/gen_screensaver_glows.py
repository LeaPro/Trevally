#!/usr/bin/env python3
"""Generates screensaver_glow_portrait.cpp / screensaver_glow_landscape.cpp from the PNGs next to this script.

The PNGs are the glow of the weather and clock screensavers' background (Figma "Screensaver Weather": the blurred
"Volume Status" ellipses and the glow around the knob) as a mask: white, with alpha = the glow's brightness in the
Figma render over black, 0-80 scaled to 0-255. screensaver.cpp tints it per theme. They are embedded as PNG data
(LV_COLOR_FORMAT_RAW, decoded by LVGL's lodepng decoder): far smaller than raw pixels, and no RGB565 banding.

  python3 gen_screensaver_glows.py        (run from this directory)
"""
import struct

for name in ("screensaver_glow_portrait", "screensaver_glow_landscape"):
    data = open(name + ".png", "rb").read()
    w, h = struct.unpack(">II", data[16:24])
    rows = ",\n".join("    " + ",".join("0x%02x" % b for b in data[i:i + 32]) for i in range(0, len(data), 32))
    with open(name + ".cpp", "w") as f:
        f.write(f"""/* Generated by gen_screensaver_glows.py from {name}.png: do not edit. */
#include "lvgl/lvgl.h"

static const uint8_t {name}_png[] = {{
{rows}
}};

extern const lv_image_dsc_t {name} = {{
  .header = {{
    .magic = LV_IMAGE_HEADER_MAGIC,
    .cf = LV_COLOR_FORMAT_RAW,
    .flags = 0,
    .w = {w},
    .h = {h},
    .stride = 0,
    .reserved_2 = 0,
  }},
  .data_size = sizeof({name}_png),
  .data = {name}_png,
  .reserved = NULL,
}};
""")
    print(name, w, h, len(data))
